def format_subscription_info(
    status: str,
    expires_at: str | None,
    price: int,
    days: int | None = None,
    last_amount: int | None = None,
    last_date: str | None = None,
    tokens: int = 0,
    monthly_active: bool = False,
) -> str:
    """Форматирует информационный блок о подписке."""
    lines = [SUBSCRIPTION_INFO_TITLE, ""]
    lines.append(f"📊 Статус: {status}")

    if monthly_active and expires_at:
        lines.append(SUBSCRIPTION_ACTIVE.format(expires_at=expires_at))
    elif monthly_active and expires_at is None:
        lines.append(SUBSCRIPTION_ACTIVE_FOREVER)

    lines.append(SUBSCRIPTION_PRICE_LABEL.format(price=price))

    if days is not None and days > 0:
        lines.append(SUBSCRIPTION_DURATION_DAYS.format(days=days))
    elif days is None and monthly_active:
        lines.append(SUBSCRIPTION_DURATION_FOREVER)

    if tokens > 0:
        lines.append(TOKEN_COUNT_LABEL.format(count=tokens))

    if last_amount is not None and last_date is not None:
        lines.append(
            SUBSCRIPTION_LAST_PAYMENT.format(amount=last_amount, date=last_date)
        )

    return "\n".join(lines)


def format_subscription_prompt(price: int) -> str:
    """Форматирует приглашение оформить подписку."""
    return SUBSCRIPTION_PROMPT.format(price=price)


