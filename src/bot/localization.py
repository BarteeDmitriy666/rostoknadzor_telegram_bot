def format_admin_user_info(detail: dict) -> str:
    """Форматирует информацию о пользователе для админ-панели."""
    sub = detail.get("subscription")
    if sub and sub.status == "active":
        sub_status = SUBSCRIPTION_STATUS_ACTIVE
        sub_expires = str(sub.expires_at) if sub.expires_at else "навсегда"
    else:
        sub_status = SUBSCRIPTION_STATUS_INACTIVE
        sub_expires = ADMIN_USER_NO_SUB

    tokens = sub.tokens if sub else 0

    name_parts = [detail.get("first_name") or "", detail.get("last_name") or ""]
    name = " ".join(p for p in name_parts if p).strip() or detail.get("username") or "Без имени"

    return ADMIN_USER_INFO.format(
        name=name,
        telegram_id=detail["telegram_id"],
        created_at=detail.get("created_at", "—"),
        forecasts_count=detail.get("forecasts_count", 0),
        sub_status=sub_status,
        sub_expires=sub_expires,
        tokens=tokens,
    )


